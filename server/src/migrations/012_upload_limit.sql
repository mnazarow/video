-- 1.10.1: предел размера загружаемого файла поднят до 2 ТБ.
-- Меняем только те установки, где значение осталось прежним по умолчанию (8192 МБ),
-- чтобы не перебивать осознанно выставленный администратором лимит.
UPDATE settings SET value = '2097152'::jsonb, updated_at = now()
 WHERE key = 'upload.max_size_mb' AND value::text IN ('8192', '"8192"');
